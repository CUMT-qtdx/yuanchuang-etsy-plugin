test('删除创作实际清理整个商品目录及队列缓存，刷新不恢复，不影响另一组', async t => {
  const { workflow, queue, root, counts } = await setup(t)
  const first = await workflow.start(input({ count: 2 }))
  await workflow.idle()
  const second = await workflow.start(input({ count: 1 }))
  await workflow.idle()
  const before = { ...counts }
  assert.ok(queue.list().some(task => task.request.projectId === first.id))
  await workflow.remove(first.id)
  await assert.rejects(access(path.join(root, first.id)), { code: 'ENOENT' })
  assert.ok(!queue.list().some(task => task.request.projectId === first.id))
  assert.equal((await workflow.list()).length, 1)
  assert.equal((await new EtsyStore(root).load())[0].id, second.id)
  const retained = await workflow.get(second.id)
  await access(path.join(root, retained.id, retained.images[0].files[0]))
  assert.deepEqual(counts, before)
  await workflow.remove(first.id)
  await assert.rejects(workflow.remove('../../outside'), /无效/)
})
