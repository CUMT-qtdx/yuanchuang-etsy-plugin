const setup = async (t, options) => {
  const root = await mkdtemp(path.join(tmpdir(), 'etsy-workflow-'))
  const context = fixture(root, options)
  await context.workflow.ready
  t.after(async () => { context.workflow.dispose(); await context.workflow.idle(); await rm(root, { recursive: true, force: true }) })
  return { ...context, root }
}
test('阶段 1/2：一次六图分别质检、只生成一份五标题文案，并保留原图', async t => {
  const { workflow, counts, root, queue, duplicate } = await setup(t)
  const request = input()
  const initial = await workflow.start(request)
  await workflow.idle()
  const product = await workflow.get(initial.id)
  assert.deepEqual(counts, { generation: 6, quality: 6, copy: 1 })
  assert.equal(product.images.filter(image => image.report?.status === 'PASS').length, 6)
  assert.equal(product.copy.titles.length, 5)
  assert.equal(product.copyStage.status, 'completed')
  assert.equal(product.referenceFiles.length, 1)
  assert.equal(product.images.flatMap(image => image.files).length, 6)
  assert.equal(product.calls.length, 13)
  assert.ok(!JSON.stringify(product).includes(modelConfig.apiKey))
  await workflow.start(request)
  for (const task of queue.list()) { duplicate(task); duplicate(task) }
  await workflow.idle()
  assert.deepEqual(counts, { generation: 6, quality: 6, copy: 1 }, '重复提交／重复完成通知不能额外计费')
  const store = new EtsyStore(root)
  const restored = await store.load()
  assert.equal(restored[0].copy.description, product.copy.description)
  assert.ok((await store.readImage(product.id, product.referenceFiles[0])).data.length > 0)
  const zip = await exportProduct(product, store)
  assert.equal(zip.readUInt32LE(0), 0x04034b50)
  assert.ok(zip.includes(Buffer.from('listing.txt')))
  assert.ok(zip.includes(Buffer.from('product.json')))
  assert.equal((await workflow.get(product.id)).images.length, 6)
})
test('质检与文案异步并行，视觉请求未结束时文案可先完成', async t => {
  let release
  const gate = new Promise(resolve => { release = resolve })
  const { workflow, counts } = await setup(t, { vision: async () => { await gate; return validateQuality({ status: 'REVISE', summary: '建议修正', issues: [{ area: '耳朵', problem: '轮廓可疑', suggestion: '修正耳朵', evidence: '视觉观察' }] }, facts, true, 'mock') } })
  const product = await workflow.start(input({ count: 1 }))
  for (let i = 0; i < 100 && counts.copy === 0; i++) await new Promise(resolve => setTimeout(resolve, 10))
  assert.equal(counts.copy, 1)
  assert.equal((await workflow.get(product.id)).copyStage.status, 'completed')
  release(); await workflow.idle()
  assert.equal((await workflow.get(product.id)).images[0].report.status, 'REVISE')
})
