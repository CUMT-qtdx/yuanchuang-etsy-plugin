test('关联生图历史按项目清理真实图片文件，其他项目的历史不变', async t => {
  const directory = await mkdtemp(path.join(tmpdir(), 'etsy-owned-history-'))
  const previous = imageDataRoot(); setImageDataRoot(directory)
  t.after(async () => { setImageDataRoot(previous); await rm(directory, { recursive: true, force: true }) })
  const entry = (id, projectId) => ({ ...input().generation, id, projectId, createdAt: Date.now(), images: [{ b64: pixel, mime: 'image/png' }] })
  await appendHistory(entry('owned-entry', 'owned-project'))
  await appendHistory(entry('retained-entry', 'retained-project'))
  const original = await listHistory()
  const removedFile = path.basename(original.find(row => row.id === 'owned-entry').images[0].url)
  const keptFile = path.basename(original.find(row => row.id === 'retained-entry').images[0].url)
  await removeProjectHistory('owned-project')
  await assert.rejects(access(path.join(directory, 'images', removedFile)), { code: 'ENOENT' })
  await access(path.join(directory, 'images', keptFile))
  assert.deepEqual((await listHistory()).map(row => row.id), ['retained-entry'])
})
